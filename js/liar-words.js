/**
 * 무작위 카테고리와 제시어 1개 뽑기
 */
export function getRandomWordEntry() {
  const cat = WORD_DATABASE[Math.floor(Math.random() * WORD_DATABASE.length)];
  const item = cat.words[Math.floor(Math.random() * cat.words.length)];
  return {
    category: cat.category,
    word: item.word,
    hints: item.hints
  };
}

